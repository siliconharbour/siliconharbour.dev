import { writeFileSync } from "node:fs";
import {
  DEFAULT_THEME,
  HARBOUR_PALETTE,
  SPACING_STEPS,
  spacingName,
  themeVariables,
} from "../app/theme/tokens";

const aliases: Record<string, string> = {
  "color-page": "page",
  "color-surface": "surface",
  "color-body": "body",
  "color-heading": "heading",
  "color-muted": "muted",
  "color-line": "border",
  "color-control-line": "control-border",
  "color-primary": "harbour-600",
  "color-primary-hover": "harbour-700",
  "color-soft": "harbour-50",
  "color-tint": "harbour-100",
  "color-subtle": "harbour-400",
  "font-sans": "font-body",
  "font-heading": "font-heading",
  "radius-control": "control-radius",
  "radius-panel": "panel-radius",
};
for (const shade of Object.keys(HARBOUR_PALETTE))
  aliases[`color-harbour-${shade}`] = `harbour-${shade}`;
for (const step of SPACING_STEPS) {
  const name = spacingName(step);
  aliases[`spacing-pad-${name}`] = `pad-${name}`;
  aliases[`spacing-gap-${name}`] = `gap-${name}`;
}
const css = `/* Generated by scripts/generate-theme.ts from app/theme/tokens.ts. */\n:root {\n${Object.entries(
  themeVariables(DEFAULT_THEME),
)
  .map(([name, value]) => `  ${name}: ${value};`)
  .join("\n")}\n}\n\n@theme inline {\n${Object.entries(aliases)
  .map(([name, target]) => `  --${name}: var(--theme-${target});`)
  .join("\n")}\n}\n`;
writeFileSync("app/styles/theme.css", css);
